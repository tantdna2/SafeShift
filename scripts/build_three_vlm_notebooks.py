"""Reproducible stdlib notebook builder, embedding only reviewed runtime sources."""
import base64
import hashlib
import json
from pathlib import Path
import zlib

from safeshift.pilot.contract import MODELS, source_digest, source_files

ROOT = Path(__file__).resolve().parents[1]


def notebook(key, repo=ROOT, preflight=False, environment=False):
    if preflight and environment:
        raise ValueError("ONE_PREFLIGHT_KIND_ONLY")
    payload = {p: (repo / p).read_bytes().decode("utf-8") for p in source_files(repo)}
    encoded = base64.b64encode(zlib.compress(json.dumps(payload, sort_keys=True).encode(), 9)).decode()
    checksum = source_digest(repo)
    code = f'''# Generated by scripts/build_three_vlm_notebooks.py; do not edit.
import base64, hashlib, json, pathlib, sys, zlib
payload = json.loads(zlib.decompress(base64.b64decode({encoded!r})))
expected_source_sha256 = {checksum!r}
inventory = {{p: hashlib.sha256(t.encode()).hexdigest() for p,t in payload.items()}}
actual = hashlib.sha256((json.dumps(inventory,sort_keys=True,ensure_ascii=True,separators=(",",":"),allow_nan=False)+"\\n").encode()).hexdigest()
if actual != expected_source_sha256:
    raise RuntimeError("EMBEDDED_SOURCE_CORRUPT")
root = pathlib.Path("/kaggle/working/data/processed/three_vlm_code") / actual
root.mkdir(parents=True, exist_ok=True)
for name, text in payload.items():
    p = root / name
    if pathlib.PurePosixPath(name).is_absolute() or ".." in pathlib.PurePosixPath(name).parts:
        raise RuntimeError("UNSAFE_EMBEDDED_PATH")
    p.parent.mkdir(parents=True,exist_ok=True)
    if p.exists():
        if p.read_bytes() != text.encode():
            raise RuntimeError("EXISTING_SOURCE_CHANGED")
    else:
        with p.open("xb") as stream:
            stream.write(text.encode())
sys.path.insert(0,str(root))
from safeshift.pilot.bootstrap import launch
evidence = launch({key!r}, expected_source_sha256, root, mode="PILOT")
print("Evidence directory:", evidence)
'''
    if preflight:
        code = code.replace('from safeshift.pilot.bootstrap import launch\n'
                            f'evidence = launch({key!r}, expected_source_sha256, root, mode="PILOT")',
                            'from safeshift.pilot.bootstrap import storage_preflight\n'
                            'evidence = storage_preflight()')
    if environment:
        code = code.replace('from safeshift.pilot.bootstrap import launch\n'
                            f'evidence = launch({key!r}, expected_source_sha256, root, mode="PILOT")',
                            'from safeshift.pilot.bootstrap import environment_preflight\n'
                            f'evidence = environment_preflight({key!r}, expected_source_sha256, root)')
    md = f"""# SafeShift — {MODELS[key]['id']} TRAIN PILOT v1

**PREP / NOT RUN.** 160 primary + at most 20 verified Qwen false-safe IDs.
No dataset, weights or inference is authorized by this notebook. FULL TRAIN is
locked; Save & Run All cannot promote a pilot to full execution.

After ChatGPT code review and separate Research Lead/Owner grant: attach exactly
one approved **private** `safeshift-pilot-input` bundle and `grant_{key}.json`;
Internet ON, accelerator **T4 ×2 (16 GB each)**. Only GPU0 is used in FP16/eager.
Gemma is currently BLOCKED by incomplete config/tokenizer source audit. Official
HF access plus reviewed source hashes/tokenizer audit and a regenerated release
are required before a Gemma run; a token alone cannot unlock this version. Then
enable Kaggle Secret `HF_TOKEN` with read access. Phi/Smol gates are independent.
No code, path, SHA, model revision or crop edits are required.

Scratch uses `/kaggle/tmp` and output uses `/kaggle/working`; preflight measures
both. A missing `/kaggle/tmp` is created only under the validated `/kaggle`
parent; existing or concurrently created roots are revalidated. Preflight checks
include real temporary allocation of 28 GiB + 4 GiB. Shared filesystems
need at least 32 GiB free, plus resume allowance. Allocation is released and is
not a guarantee of future quota or peak usage. Insufficient space stops before
installation. Phi remains 16 crops/FP16/eager:
T4 OOM risk is UNVERIFIED, and OOM stops instead of changing preprocessing.

The notebook kernel may be Python 3.13. It remains the stdlib supervisor only:
the pilot prefers and validates `/usr/bin/python3.12`, then an eligible Python
3.11, creates a fresh venv in scratch, and uses that exact interpreter for pip,
`pip freeze`, CPU ABI checks, model download and the worker. It never falls back
to Python 3.13 or mixes notebook site-packages into the worker.

After the CPU checks, the pilot checks T4 x2 and GPU0 free memory with
`nvidia-smi` and saves its receipt before consuming the attempt. Missing/wrong
GPUs, insufficient free memory or a failed receipt write stop with no attempt
consumption. The worker still performs the real CUDA FP16 admission afterwards.

For authorized resume also attach the exact prior archive renamed
`resume_{key}.zip` and a new source/config/input-bound resume grant. SUCCESS is
not rerun; errors/INVALID need a separate exact-ID retry grant.

Download the printed result ZIP and `.sha256.json` from Outputs, including failed
or partial attempts. `/kaggle/working` is ephemeral; Save Version/outputs and
download immediately. Owned scratch is cleaned after the worker; if cleanup fails,
download evidence ZIP only, never publish the whole working tree with cache/weights.
See `docs/KAGGLE_THREE_VLM_PILOT.md` in the same Draft PR.
Classification and HNLO statuses are independent. CPU tests/source audit do not
prove T4 execution, HNLO alignment or pilot quality.
"""
    if preflight:
        md = """# SafeShift — CPU-only storage preflight

Run this notebook without any dataset or grant, before allocating a pilot attempt.
It does not call a GPU, download weights or execute a model. It checks
`/kaggle/tmp` and `/kaggle/working`, with exclusive temporary allocations of
28 GiB and 4 GiB concurrently. If `/kaggle/tmp` is absent, it is created safely
under the validated `/kaggle` parent; existing roots are checked and retained.
The allocations are released immediately: PASS
does not guarantee later quota, peak usage, GPU fit, or permission to run.
Download the printed `storage_preflight.json`; failure to write a receipt is
reported in the notebook output. This operation may be slow and consume capacity
temporarily. Do not start a pilot if BLOCKED or if conditions have changed.
"""
    if environment:
        md = f"""# SafeShift — {MODELS[key]['id']} CPU environment preflight

Run this notebook on the intended Kaggle image before issuing a new attempt.
It needs Internet for pinned package installation, but no dataset, grant, GPU,
model weights or inference. The Python 3.13 kernel remains the supervisor only.
The preflight prefers `/usr/bin/python3.12`, accepts only qualified Linux x86_64
CPython 3.11/3.12, creates a fresh scratch venv and uses it for the exact pinned
CUDA-wheel install, `pip check`, `pip freeze`, version checks and CPU-only native
library smoke. Missing `venv`/`ensurepip`, dependency failure, host-package
leakage or wrong versions produce a BLOCKED receipt and consume no attempt.

All venv/cache/temp bytes stay under `/kaggle/tmp`; receipts/logs and a ZIP stay
under `/kaggle/working`. Weights are not downloaded and CUDA is not called.
Download the printed ZIP and sidecar. PASS proves only this CPU environment
rehearsal at that time, not model load, T4 fit, inference or HNLO validity.
"""
    return {"cells": [{"cell_type": "markdown", "id": "instructions", "metadata": {}, "source": md.splitlines(True)},
                      {"cell_type": "code", "id": "pilot-launch", "metadata": {}, "execution_count": None, "outputs": [], "source": code.splitlines(True)}],
            "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                         "language_info": {"name": "python"},
                         "safeshift": {"mode": ("STORAGE_PREFLIGHT" if preflight else
                                                   "ENVIRONMENT_PREFLIGHT" if environment else "PILOT"),
                                       "model_key": None if preflight else key, "source_sha256": checksum}},
            "nbformat": 4, "nbformat_minor": 5}


def main():
    root = ROOT / "notebooks"
    root.mkdir(exist_ok=True)
    for key in MODELS:
        path = root / f"SafeShift_TRAIN_PILOT_{key}.ipynb"
        path.write_text(json.dumps(notebook(key), indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    path = root / "SafeShift_STORAGE_PREFLIGHT.ipynb"
    path.write_text(json.dumps(notebook("phi", preflight=True), indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    for key in ("phi", "smolvlm2"):
        path = root / f"SafeShift_ENVIRONMENT_PREFLIGHT_{key}.ipynb"
        path.write_text(json.dumps(notebook(key, environment=True), indent=1, ensure_ascii=False) + "\n",
                        encoding="utf-8", newline="\n")
    print("SOURCE_SHA256", source_digest(ROOT))


if __name__ == "__main__":
    main()
